def add_print(n):
    "1부터 n까지 누적합을 출력"
    tot = 0
    for i in range(1, n+1):
        tot += i # tot = tot+i
    print(f"1부터 {n}까지 누적합은 {tot}입니다")

def add_return(n):
    "1부터 n까지 누적합을 return"
    tot = 0
    for i in range(1, n+1):
        tot += i # tot = tot+i
    return tot




















